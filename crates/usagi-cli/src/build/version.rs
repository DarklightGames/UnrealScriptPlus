//! The generated class with the mod's version and Git commit.

use std::fs;
use std::path::Path;
use std::process::Command;

/// `MAJOR.MINOR.PATCH` and an optional `-PRERELEASE`.
#[derive(Debug, PartialEq, Eq)]
pub struct Version {
    pub major: u32,
    pub minor: u32,
    pub patch: u32,
    pub prerelease: String,
}

impl Version {
    pub fn parse(text: &str) -> Result<Self, String> {
        let error = || {
            format!(
                "invalid build.version {:?}: expected MAJOR.MINOR.PATCH[-PRERELEASE]",
                text
            )
        };
        let (numbers, prerelease) = text.split_once('-').unwrap_or((text, ""));
        let parts: Vec<u32> = numbers
            .split('.')
            .map(|n| n.parse().map_err(|_| error()))
            .collect::<Result<_, _>>()?;
        let [major, minor, patch] = parts[..] else {
            return Err(error());
        };
        if prerelease.contains('"') || text.ends_with('-') {
            return Err(error());
        }
        Ok(Version {
            major,
            minor,
            patch,
            prerelease: prerelease.to_string(),
        })
    }
}

fn git(root: &Path, args: &[&str]) -> String {
    let output = Command::new("git").args(args).current_dir(root).output();
    match output {
        Ok(output) if output.status.success() => {
            String::from_utf8_lossy(&output.stdout).trim().to_string()
        }
        _ => {
            println!("warning: `git {}` failed; leaving it empty", args.join(" "));
            String::new()
        }
    }
}

pub fn class_source(class_name: &str, version: &Version, commit: &str, branch: &str) -> String {
    format!(
        "//===============================================
// This file is generated by the build system
// Do not modify this file manually
//===============================================

class {class_name} extends Object;

var UVersion Version;
var string GitCommit;
var string GitBranch;

defaultproperties
{{
    Begin Object Class=UVersion Name=VersionObject
        Major={major}
        Minor={minor}
        Patch={patch}
        Prerelease=\"{prerelease}\"
        Metadata=\"{commit}\"
    End Object
    Version=VersionObject
    GitCommit=\"{commit}\"
    GitBranch=\"{branch}\"
}}
",
        major = version.major,
        minor = version.minor,
        patch = version.patch,
        prerelease = version.prerelease,
    )
}

/// Writes the class to `path`, unless it's unchanged (so that its package
/// isn't rebuilt every time).
pub fn write_class(root: &Path, path: &Path, version: &str) -> Result<(), String> {
    let version = Version::parse(version)?;
    let class_name = path
        .file_stem()
        .and_then(|s| s.to_str())
        .ok_or_else(|| format!("invalid build.version-class {}", path.display()))?;
    let commit = git(root, &["rev-parse", "--short", "HEAD"]);
    let branch = git(root, &["rev-parse", "--abbrev-ref", "HEAD"]);
    let source = class_source(class_name, &version, &commit, &branch);
    if fs::read(path).ok().as_deref() == Some(source.as_bytes()) {
        return Ok(());
    }
    fs::write(path, source).map_err(|e| format!("{}: {}", path.display(), e))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_versions() {
        assert_eq!(
            Version::parse("12.2.5").unwrap(),
            Version {
                major: 12,
                minor: 2,
                patch: 5,
                prerelease: String::new()
            }
        );
        assert_eq!(Version::parse("1.0.0-beta.1").unwrap().prerelease, "beta.1");
        for bad in ["1.2", "1.2.3.4", "a.b.c", "1.2.3-", "", "1.2.3-\"x"] {
            assert!(Version::parse(bad).is_err(), "{}", bad);
        }
    }

    #[test]
    fn writes_only_when_changed() {
        let dir = tempfile::TempDir::new().unwrap();
        let path = dir.path().join("MyManifest.uc");
        write_class(dir.path(), &path, "1.2.3").unwrap();
        let source = fs::read_to_string(&path).unwrap();
        assert!(source.contains("class MyManifest extends Object;"));
        assert!(source.contains("        Minor=2\n"));
        let modified = fs::metadata(&path).unwrap().modified().unwrap();
        write_class(dir.path(), &path, "1.2.3").unwrap();
        assert_eq!(fs::metadata(&path).unwrap().modified().unwrap(), modified);
    }
}
